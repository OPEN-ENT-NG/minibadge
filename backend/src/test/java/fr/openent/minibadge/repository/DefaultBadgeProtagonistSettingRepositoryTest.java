package fr.openent.minibadge.repository;

import fr.openent.minibadge.core.enums.SqlTable;
import fr.openent.minibadge.repository.impl.DefaultBadgeProtagonistSettingRepository;
import io.vertx.core.Handler;
import io.vertx.core.json.JsonArray;
import io.vertx.ext.unit.junit.VertxUnitRunner;
import org.entcore.common.sql.Sql;
import org.junit.Before;
import org.junit.Test;
import org.junit.runner.RunWith;
import org.mockito.Mock;
import org.mockito.MockitoAnnotations;
import org.powermock.reflect.Whitebox;

import java.util.Arrays;
import java.util.Collections;

import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.eq;
import static org.mockito.Mockito.*;

/**
 * Exact SQL generated by the join between badge_type_setting and badge_protagonist_setting.
 * <p>
 * Epic A shipped this query hardcoded to {@code AND bts.structure_id IS NULL}, i.e. centralized
 * configuration only. Epic B makes establishments create their own badge types, whose
 * badge_type_setting row necessarily carries a structure_id (the {@code unique_structure_type}
 * constraint is exactly that), so that filter would have hidden their protagonist rows entirely and
 * silently fallen back to the hardcoded Student-&gt;Student relation — a teacher would not have been
 * able to award a badge their own school had just created. These tests pin the replacement scoping,
 * including the precedence rule when both a centralized and a structure row exist.
 * <p>
 * {@code Sql} is NOT mocked statically here (unlike before): the query now goes through
 * {@code SqlHelper.filterStructuresWithNull} → {@code Sql.listPrepared}, and a static mock would
 * neuter that helper, making the asserted string meaningless. The instance is swapped on the
 * already-constructed repository instead.
 */
@RunWith(VertxUnitRunner.class)
public class DefaultBadgeProtagonistSettingRepositoryTest {

    private static final String QUERY_PREFIX =
            "SELECT bps.id, bps.protagonist_type_id, bps.protagonist_type " +
            "FROM " + SqlTable.BADGE_PROTAGONIST_SETTING.getName() + " bps " +
            "INNER JOIN (" +
                "SELECT id FROM " + SqlTable.BADGE_TYPE_SETTING.getName() + " " +
                "WHERE badge_type_id = ? AND ";

    private static final String QUERY_SUFFIX =
            " ORDER BY structure_id NULLS LAST, id LIMIT 1" +
            ") bts ON bps.badge_type_setting_id = bts.id";

    @Mock
    private Sql sql;

    private DefaultBadgeProtagonistSettingRepository repository;

    @Before
    @SuppressWarnings("unchecked")
    public void setUp() {
        MockitoAnnotations.initMocks(this);
        repository = new DefaultBadgeProtagonistSettingRepository();
        Whitebox.setInternalState(repository, "sql", sql);
        doNothing().when(sql).prepared(any(), any(), any(Handler.class));
    }

    /**
     * A user belonging to structures reads BOTH the centralized row and their own structures' rows.
     * The sub-select's ORDER BY is what makes a structure row win over the centralized one when a
     * badge type has both, and LIMIT 1 is what keeps the protagonist rows of exactly one setting from
     * being mixed together.
     */
    @Test
    @SuppressWarnings("unchecked")
    public void testFindByBadgeTypeIdScopesOnUserStructuresAndCentralizedRows() {
        String expectedQuery = QUERY_PREFIX
                + "(structure_id IN (?,?) OR structure_id IS NULL)"
                + QUERY_SUFFIX;
        JsonArray expectedParams = new JsonArray().add(42L).add("structure1").add("structure2");

        repository.findByBadgeTypeId(42L, Arrays.asList("structure1", "structure2"));

        verify(sql).prepared(eq(expectedQuery), eq(expectedParams), any(Handler.class));
    }

    /**
     * No structures (e.g. an unattached user): only the centralized row remains eligible, which is
     * exactly the pre-Epic-B behaviour — no regression for the centrally-seeded badge types.
     */
    @Test
    @SuppressWarnings("unchecked")
    public void testFindByBadgeTypeIdFallsBackToCentralizedRowWhenUserHasNoStructure() {
        String expectedQuery = QUERY_PREFIX + "(  structure_id IS NULL)" + QUERY_SUFFIX;
        JsonArray expectedParams = new JsonArray().add(42L);

        repository.findByBadgeTypeId(42L, Collections.emptyList());

        verify(sql).prepared(eq(expectedQuery), eq(expectedParams), any(Handler.class));
    }

    @Test
    @SuppressWarnings("unchecked")
    public void testFindByBadgeTypeIdHandlesNullStructureList() {
        String expectedQuery = QUERY_PREFIX + "(  structure_id IS NULL)" + QUERY_SUFFIX;
        JsonArray expectedParams = new JsonArray().add(42L);

        repository.findByBadgeTypeId(42L, null);

        verify(sql).prepared(eq(expectedQuery), eq(expectedParams), any(Handler.class));
    }
}
