package fr.openent.minibadge.service;

import fr.openent.minibadge.model.BadgeType;
import io.vertx.core.Future;
import org.entcore.common.user.UserInfos;

import java.util.List;

public interface BadgeTypeService {

    /**
     * Stable failure message a {@link #create(BadgeType, List)} rejects with when the generated
     * {@code slug} collides with an existing one despite the de-duplication trigger
     * (sql/023-fix-badge-type-slug-trigger.sql). Doubles as the i18n key the controller renders,
     * so the client gets an actionable "this label is already taken" instead of an opaque 500.
     */
    String DUPLICATE_SLUG_ERROR = "minibadge.error.badge.type.duplicate";

    /**
     * Get list of general / structure based badge types
     *
     * @param structureIds Structure identifiers
     * @param limit        max number of occurrences
     * @param offset       position from where getting occurrences
     * @param query        search query
     * @param badgeCategoryId filter on badge category id
     * @return return list of badge type (model)
     */
    Future<List<BadgeType>> getBadgeTypes(List<String> structureIds, String query, int limit, Integer offset, Long badgeCategoryId);

    /**
     * Get badge type
     *
     * @param userInfos    User information
     * @param typeId       Type identifier
     * @param host         Host
     * @param language     accepted language
     * @return return list of badge type (model)
     */
    Future<BadgeType> getBadgeType(UserInfos userInfos, long typeId, String host, String language);

    /**
     * Create a badge type owned by one structure, together with every companion row it needs to be
     * immediately usable: its {@code badge_type_setting}, the {@code badge_protagonist_setting} rows
     * behind its assignation relations (same profiles as the centrally-seeded types, so a local badge
     * behaves like a central one instead of silently falling back to Student-&gt;Student), and its
     * {@code rel_badge_category_badge_type} links.
     * <p>
     * Those four inserts form a 3-level chain — each level needs the previous one's generated id — and
     * are issued as a SINGLE chained-CTE statement, hence atomically. A sequence of separate inserts
     * could leave an orphan badge type behind on partial failure, and minibadge exposes no delete
     * endpoint at all: such an orphan would be unremovable without manual SQL.
     *
     * @param badgeType   the type to create; {@code structureId} MUST already be validated against the
     *                    creator's own structures, and {@code ownerId} set to the creator. {@code slug}
     *                    is never sent — it is generated by the badge_type trigger.
     * @param categoryIds the badge categories to link; ids with no matching row are ignored rather than
     *                    failing the whole creation.
     * @return the created badge type (id and generated slug included). Fails with
     * {@link #DUPLICATE_SLUG_ERROR} on a slug collision.
     */
    Future<BadgeType> create(BadgeType badgeType, List<Long> categoryIds);
}
