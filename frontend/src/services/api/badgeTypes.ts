import { odeServices } from '@edifice.io/client';

import { BadgeType } from '~/models/badgeType';
import { MinibadgeUser } from '~/models/user';
import { request } from '~/services/api/http';

/**
 * Response envelope of `GET /types` — offset/limit pagination, verified in
 * `BadgeTypeController.java#getBadgeTypes` + `RequestHelper.formatResponse(limit, offset, list)`.
 */
export interface BadgeTypesPage {
  all: BadgeType[];
  limit: number;
  offset: number;
}

/**
 * GET /types — verified in `BadgeTypeController.java#getBadgeTypes`.
 * `offset` is required server-side (`Integer.parseInt(...)` with no default,
 * throws `NumberFormatException` if absent).
 */
export const getBadgeTypes = async (
  offset: number,
  limit?: number,
  query?: string,
  categoryId?: number,
): Promise<BadgeTypesPage> => {
  const response = await request(() =>
    odeServices.http().get<BadgeTypesPage>('/minibadge/types', {
      queryParams: { offset, limit, query, categoryId },
      disableNotifications: true,
    }),
  );
  return response;
};

/**
 * GET /minibadge/types/:typeId — verified in `BadgeTypeController.java#getBadgeType`.
 * Renders `badgeType.toJson()` directly (not wrapped in `{ all }`).
 */
export const getBadgeType = async (typeId: number): Promise<BadgeType> => {
  const response = await request(() =>
    odeServices.http().get<BadgeType>(`/minibadge/types/${typeId}`, {
      disableNotifications: true,
    }),
  );
  return response;
};

/**
 * Body of `POST /minibadge/types` — verified against `jsonschema/badgeTypeCreate.json`
 * (`additionalProperties: false`, only `label` required).
 *
 * `structureId` is optional and only ever a HINT: the server validates it against the caller's own
 * structures and derives it when the caller belongs to exactly one, so omitting it is the normal case
 * for a single-establishment admin. `slug` is not part of this body at all — it is generated by a
 * database trigger.
 */
export interface BadgeTypeCreatePayload {
  label: string;
  description?: string;
  descriptionShort?: string;
  pictureId?: string;
  structureId?: string;
  categoryIds?: number[];
}

/**
 * POST /minibadge/types — verified in `BadgeTypeController.java#createBadgeType`.
 * Responds 201 with the created badge type.
 */
export const createBadgeType = async (payload: BadgeTypeCreatePayload): Promise<BadgeType> => {
  const response = await request(() =>
    odeServices.http().post<BadgeType>('/minibadge/types', payload, {
      disableNotifications: true,
    }),
  );
  return response;
};

